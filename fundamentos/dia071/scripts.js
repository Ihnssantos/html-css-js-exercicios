let a = 10;
let b = 5;

console.log(a > b); //maior
console.log(a < b); //menor
console.log(a >= b); //maior ou igual
console.log(a <= b); //menor ou igual
console.log(a == b); //igual em valor
console.log(a === b); //igual em valor e tipo de dado
console.log(a != b); //diferente em valor
console.log(a !== b); //diferente em valor ou tipo de dado